-- Query 1: Total Customers
-- Business Question:
-- How many customers are present in the banking dataset?

SELECT
    COUNT(*) AS total_customers
FROM customers;


-- Query 2: Active Customers
-- Business Definition:
-- A customer is considered active if they have at least
-- one transaction during 2025.

SELECT
    COUNT(DISTINCT a.customer_id) AS active_customers
FROM accounts a
JOIN transactions t
    ON a.account_id = t.account_id;


-- Query 3: Total Transactions
-- Business Question:
-- How many transactions occurred during the analysis period?

SELECT
    COUNT(*) AS total_transactions
FROM transactions;


-- Query 4: Total Transaction Value
-- Business Question:
-- What is the total value of all transactions?

SELECT
    ROUND(SUM(amount), 2) AS total_transaction_value
FROM transactions;


-- Query 5: Average Transaction Value
-- Business Question:
-- What is the average value of a transaction?

SELECT
    ROUND(AVG(amount), 2) AS average_transaction_value
FROM transactions;


/*
============================================================
SECTION 2: CUSTOMER ANALYSIS
============================================================
*/


-- Query 6: Customers by Segment
-- Business Question:
-- How is the customer base distributed across segments?

SELECT
    segment,
    COUNT(*) AS customer_count
FROM customers
GROUP BY segment
ORDER BY customer_count DESC;


-- Query 7: Customers by City
-- Business Question:
-- Which cities have the largest customer populations?

SELECT
    city,
    COUNT(*) AS customer_count
FROM customers
GROUP BY city
ORDER BY customer_count DESC;


-- Query 8: Customers by Age Group
-- Business Question:
-- How is the customer base distributed by age group?

SELECT
    age_group,
    COUNT(*) AS customer_count
FROM customers
GROUP BY age_group
ORDER BY customer_count DESC;


-- Query 9: Customer Distribution by Segment and Age Group
-- Business Question:
-- How are different age groups distributed within
-- each customer segment?

SELECT
    segment,
    age_group,
    COUNT(*) AS customer_count
FROM customers
GROUP BY
    segment,
    age_group
ORDER BY
    segment,
    customer_count DESC;


-- Query 10: Average Age by Customer Segment
-- Business Question:
-- What is the average age of customers in each segment?

SELECT
    segment,
    ROUND(AVG(age), 1) AS average_age,
    COUNT(*) AS customer_count
FROM customers
GROUP BY segment
ORDER BY average_age;


