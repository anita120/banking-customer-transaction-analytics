-- Query 11: Active Customers by Segment
-- Business Question:
-- How many customers in each segment are actively
-- using their accounts?

SELECT
    c.segment,
    COUNT(DISTINCT c.customer_id) AS active_customers
FROM customers c
JOIN accounts a
    ON c.customer_id = a.customer_id
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY c.segment
ORDER BY active_customers DESC;


-- Query 12: Transaction Count by Customer Segment
-- Business Question:
-- How many transactions are generated by each
-- customer segment?

SELECT
    c.segment,
    COUNT(t.transaction_id) AS transaction_count
FROM customers c
JOIN accounts a
    ON c.customer_id = a.customer_id
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY c.segment
ORDER BY transaction_count DESC;


-- Query 13: Transaction Value by Customer Segment
-- Business Question:
-- What is the total transaction value generated
-- by each customer segment?

SELECT
    c.segment,
    ROUND(SUM(t.amount), 2) AS total_transaction_value
FROM customers c
JOIN accounts a
    ON c.customer_id = a.customer_id
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY c.segment
ORDER BY total_transaction_value DESC;


-- Query 14: Average Transaction Value by Segment
-- Business Question:
-- Does transaction size differ significantly across
-- customer segments?

SELECT
    c.segment,
    ROUND(AVG(t.amount), 2) AS average_transaction_value,
    COUNT(t.transaction_id) AS transaction_count
FROM customers c
JOIN accounts a
    ON c.customer_id = a.customer_id
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY c.segment
ORDER BY average_transaction_value DESC;


