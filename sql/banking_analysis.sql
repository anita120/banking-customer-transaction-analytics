-- Query 15: Monthly Transaction Trend
-- Business Question:
-- How does transaction volume and transaction value
-- change over the year?

SELECT
    transaction_month,
    COUNT(*) AS transaction_count,
    ROUND(SUM(amount), 2) AS transaction_value
FROM transactions
GROUP BY transaction_month
ORDER BY transaction_month;


-- Query 16: Debit vs Credit Transactions
-- Business Question:
-- How do debit and credit transactions compare
-- in volume and value?

SELECT
    transaction_type,
    COUNT(*) AS transaction_count,
    ROUND(SUM(amount), 2) AS transaction_value,
    ROUND(AVG(amount), 2) AS average_transaction_value
FROM transactions
GROUP BY transaction_type
ORDER BY transaction_count DESC;


-- Query 17: Transactions by Channel
-- Business Question:
-- Which transaction channels are used most frequently
-- and generate the highest transaction value?

SELECT
    channel,
    COUNT(*) AS transaction_count,
    ROUND(SUM(amount), 2) AS transaction_value,
    ROUND(AVG(amount), 2) AS average_transaction_value
FROM transactions
GROUP BY channel
ORDER BY transaction_count DESC;


-- Query 18: High-Value Transactions
-- Business Question:
-- How many transactions exceed the analytical
-- high-value threshold of ₹50,000?

SELECT
    COUNT(*) AS high_value_transactions,
    ROUND(SUM(amount), 2) AS high_value_transaction_value,
    ROUND(AVG(amount), 2) AS average_high_value_transaction
FROM transactions
WHERE amount > 50000;


-- Query 19: Largest Individual Transactions
-- Business Question:
-- Which individual transactions have the highest values?

SELECT
    transaction_id,
    account_id,
    transaction_date,
    transaction_type,
    amount,
    channel
FROM transactions
ORDER BY amount DESC
LIMIT 10;


/*
============================================================
SECTION 5: PRODUCT ANALYSIS
============================================================

IMPORTANT DATA MODEL NOTE:

The customer_products table identifies which products
customers have, but transactions do not contain product_id.

Therefore, transaction value should NOT be directly
attributed to products.

The following analysis focuses on product adoption
and customer activity associated with product ownership.
============================================================
*/


-- Query 20: Customers by Product
-- Business Question:
-- How many customers are associated with each product?

SELECT
    p.product_name,
    COUNT(DISTINCT cp.customer_id) AS customer_count
FROM customer_products cp
JOIN products p
    ON cp.product_id = p.product_id
GROUP BY p.product_name
ORDER BY customer_count DESC;


-- Query 21: Active Customers and Activity Rate by Product
-- Business Question:
-- What percentage of customers associated with each
-- product are active?

WITH product_customers AS (
    SELECT
        cp.product_id,
        COUNT(DISTINCT cp.customer_id) AS total_customers
    FROM customer_products cp
    GROUP BY cp.product_id
),

active_product_customers AS (
    SELECT
        cp.product_id,
        COUNT(DISTINCT cp.customer_id) AS active_customers
    FROM customer_products cp
    JOIN accounts a
        ON cp.customer_id = a.customer_id
    JOIN transactions t
        ON a.account_id = t.account_id
    GROUP BY cp.product_id
)

SELECT
    p.product_name,
    pc.total_customers,
    COALESCE(apc.active_customers, 0) AS active_customers,
    ROUND(
        COALESCE(apc.active_customers, 0) * 100.0
        / pc.total_customers,
        2
    ) AS activity_rate
FROM products p
JOIN product_customers pc
    ON p.product_id = pc.product_id
LEFT JOIN active_product_customers apc
    ON p.product_id = apc.product_id
ORDER BY activity_rate DESC;


