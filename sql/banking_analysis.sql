-- Query 22: Transactions by Account Type
-- Business Question:
-- Which account types generate the highest transaction
-- volume and transaction value?

SELECT
    a.account_type,
    COUNT(t.transaction_id) AS transaction_count,
    ROUND(SUM(t.amount), 2) AS transaction_value,
    ROUND(AVG(t.amount), 2) AS average_transaction_value
FROM accounts a
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY a.account_type
ORDER BY transaction_count DESC;


-- Query 23: Account Type by Transaction Type
-- Business Question:
-- How do debit and credit transaction patterns
-- differ across account types?

SELECT
    a.account_type,
    t.transaction_type,
    COUNT(t.transaction_id) AS transaction_count,
    ROUND(SUM(t.amount), 2) AS transaction_value,
    ROUND(AVG(t.amount), 2) AS average_transaction_value
FROM accounts a
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY
    a.account_type,
    t.transaction_type
ORDER BY
    a.account_type,
    t.transaction_type;


