-- Query 24: Top Customers by Transaction Activity
-- Business Question:
-- Which customers have the highest transaction frequency
-- and what is the value of their transactions?

SELECT
    c.customer_id,
    c.customer_name,
    c.segment,
    COUNT(t.transaction_id) AS transaction_count,
    ROUND(SUM(t.amount), 2) AS total_transaction_value,
    ROUND(AVG(t.amount), 2) AS average_transaction_value
FROM customers c
JOIN accounts a
    ON c.customer_id = a.customer_id
JOIN transactions t
    ON a.account_id = t.account_id
GROUP BY
    c.customer_id,
    c.customer_name,
    c.segment
ORDER BY transaction_count DESC
LIMIT 10;


-- Query 25: Customer Activity Buckets
-- Business Question:
-- How are active customers distributed by
-- transaction frequency?
--
-- Activity Definitions:
-- 1-10 transactions   = Low Activity
-- 11-30 transactions  = Moderate Activity
-- 31-60 transactions  = High Activity
-- 61+ transactions    = Very High Activity

WITH customer_activity AS (
    SELECT
        c.customer_id,
        COUNT(t.transaction_id) AS transaction_count
    FROM customers c
    JOIN accounts a
        ON c.customer_id = a.customer_id
    JOIN transactions t
        ON a.account_id = t.account_id
    GROUP BY c.customer_id
),

activity_buckets AS (
    SELECT
        CASE
            WHEN transaction_count BETWEEN 1 AND 10
                THEN 'Low Activity'

            WHEN transaction_count BETWEEN 11 AND 30
                THEN 'Moderate Activity'

            WHEN transaction_count BETWEEN 31 AND 60
                THEN 'High Activity'

            ELSE 'Very High Activity'
        END AS activity_level
    FROM customer_activity
)

SELECT
    activity_level,
    COUNT(*) AS customer_count
FROM activity_buckets
GROUP BY activity_level
ORDER BY
    CASE
        WHEN activity_level = 'Low Activity' THEN 1
        WHEN activity_level = 'Moderate Activity' THEN 2
        WHEN activity_level = 'High Activity' THEN 3
        WHEN activity_level = 'Very High Activity' THEN 4
    END;


